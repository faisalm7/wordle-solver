#!/usr/bin/env python3
"""Pack the word lists into a C++ header."""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[1]
WORD = re.compile(r"[a-z]{5}\Z")


def read_words(path: Path) -> tuple[list[str], str]:
    raw = path.read_bytes()
    try:
        words = raw.decode("ascii").splitlines()
    except UnicodeDecodeError as error:
        raise ValueError(f"{path}: expected lowercase ASCII words") from error
    if not words:
        raise ValueError(f"{path}: dictionary is empty")
    for line, word in enumerate(words, 1):
        if not WORD.fullmatch(word):
            raise ValueError(f"{path}:{line}: expected exactly five lowercase letters")
    if len(set(words)) != len(words):
        raise ValueError(f"{path}: dictionary contains duplicate words")
    return words, hashlib.sha256(raw).hexdigest()


def packed_array(name: str, words: list[str]) -> str:
    rows = ["".join(words[i : i + 20]) for i in range(0, len(words), 20)]
    return (f"inline constexpr char {name}[] =\n"
            + "\n".join('    "' + row + '"' for row in rows) + ";\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--answers", type=Path, default=ROOT / "data/answers.txt")
    parser.add_argument("--guesses", type=Path, default=ROOT / "data/guesses.txt")
    parser.add_argument("--output", type=Path, default=ROOT / "build/generated/words.hpp")
    args = parser.parse_args()
    try:
        answers, answer_hash = read_words(args.answers)
        guesses, guess_hash = read_words(args.guesses)
        missing = set(answers) - set(guesses)
        if missing:
            raise ValueError("answers missing from guesses: " + ", ".join(sorted(missing)[:5]))
    except (OSError, ValueError) as error:
        parser.error(str(error))

    header = (
        "// Generated by scripts/embed_words.py. Do not edit.\n"
        "// Word lists from Alex Selby; see data/LICENSE-alex1770.txt.\n"
        f"// answers SHA-256: {answer_hash}\n"
        f"// guesses SHA-256: {guess_hash}\n"
        "#pragma once\n\n#include <string>\n#include <string_view>\n#include <vector>\n\n"
        "namespace wordle::data {\nnamespace detail {\n\n"
        + packed_array("kAnswerWords", answers) + "\n" + packed_array("kGuessWords", guesses)
        + "\ninline std::vector<std::string> unpack(std::string_view packed) {\n"
          "    std::vector<std::string> result;\n"
          "    result.reserve(packed.size() / 5);\n"
          "    for (std::size_t i = 0; i < packed.size(); i += 5)\n"
          "        result.emplace_back(packed.data() + i, 5);\n"
          "    return result;\n}\n\n} // namespace detail\n\n"
          "inline std::vector<std::string> answers() {\n"
          "    return detail::unpack({detail::kAnswerWords, sizeof(detail::kAnswerWords) - 1});\n}\n"
          "inline std::vector<std::string> guesses() {\n"
          "    return detail::unpack({detail::kGuessWords, sizeof(detail::kGuessWords) - 1});\n}\n"
        + "\n} // namespace wordle::data\n"
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    # Avoid changing the timestamp when the generated content is already current.
    if not args.output.exists() or args.output.read_bytes() != header.encode("ascii"):
        args.output.write_bytes(header.encode("ascii"))


if __name__ == "__main__":
    main()
